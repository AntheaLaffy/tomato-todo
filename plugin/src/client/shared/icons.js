export const ICON_NAMES = Object.keys(ICONS);

/**
 * Icon({name, size=20, stroke=1.7, style})
 * 未知名字渲染空 svg（不抛错，避免整块 slot 因图标名塌掉）。
 */
export function Icon({ name, size = 20, stroke = 1.7, style }) {
  const shapes = ICONS[name] || [];
  return h(
    "svg",
    {
      width: size,
      height: size,
      viewBox: "0 0 24 24",
      fill: "none",
      stroke: "currentColor",
      strokeWidth: stroke,
      strokeLinecap: "round",
      strokeLinejoin: "round",
      "aria-hidden": "true",
      style: { display: "block", flex: "none", ...style },
    },
    shapes.map(([tag, props], i) => h(tag, { key: i, ...props })),
  );
}
