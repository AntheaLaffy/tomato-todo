// 客户端构建：把 plugin/src/client/** 打成 plugin/client.js。
//
// 为什么需要构建：DSH 的客户端半只有一个入口文件（package.json 里
// exports["./client"]），而番茄的界面已远超单文件能维护的规模。源码按
// 职责分目录，esbuild 负责把 ESM 依赖收成一个 IIFE；工厂函数所需的
// `require("react")` 由 entry.js 在运行时注入，所以 react 不参与打包。
//
// 产物必须保持「脚本执行时只调用 window.__ModuleLoader__.load 注册工厂」的
// 契约（见 dsh-client-modules 的 lazy CJS 模型），因此 entry.js 是唯一顶层
// 语句入口，其余模块只导出符号。
import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outfile = join(root, "plugin/client.js");

const result = await build({
  entryPoints: [join(root, "plugin/src/client/entry.js")],
  outfile,
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2022"],
  charset: "utf8",
  legalComments: "none",
  minify: false,
  sourcemap: false,
  logLevel: "warning",
  banner: {
    js: [
      "// Client half of @local/tomato-dsh — GENERATED by scripts/build-client.mjs.",
      "// Edit plugin/src/client/** instead; do not hand-edit this file.",
      `// build: ${new Date().toISOString()}`,
    ].join("\n"),
  },
  metafile: true,
});

const inputs = Object.keys(result.metafile.inputs).length;
const bytes = result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].bytes;
console.log(`client.js built from ${inputs} modules (${(bytes / 1024).toFixed(1)} KiB)`);
