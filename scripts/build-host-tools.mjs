// Ship the runtime MCP tool contract with the independently installed DSH plugin.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { TOOLS } from "../runtime/src/tools.mjs";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const target = join(root, "plugin", "host-tool-specs.js");
const specs = TOOLS.map(({ name, description, inputSchema }) => ({
  name, description, inputSchema,
}));
const source = `// Generated by scripts/build-host-tools.mjs; do not edit by hand.\n` +
  `export const HOST_TOOL_SPECS = ${JSON.stringify(specs, null, 2)};\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== source) {
    console.error("plugin/host-tool-specs.js is stale; run pnpm build:host-tools");
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, source);
}
